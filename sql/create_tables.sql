-- Tables for database swing_trade_edition_2
-- Run in pgAdmin: Query Tool on swing_trade_edition_2

-- 1. swingbot/database.py -> save_trade()
CREATE TABLE IF NOT EXISTS public.swing_trades_table (
    id             bigserial PRIMARY KEY,
    symbol         varchar(30) NOT NULL,
    direction      varchar(5)  NOT NULL CHECK (direction IN ('LONG', 'SHORT')),
    entry_time     time NOT NULL,
    exit_time      time NOT NULL,
    entry_price    double precision NOT NULL,
    exit_price     double precision NOT NULL,
    pnl_pct        double precision NOT NULL,
    mae_pct        double precision NOT NULL,
    duration_hours double precision NOT NULL,
    checked_time   date,
    UNIQUE (symbol, direction, entry_time, exit_time)
);

-- 2. swingbot/database.py insert_paper_trade() (insert), reports/google_drive.py "paper" (read)
CREATE TABLE IF NOT EXISTS public.trading_paper (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol         text NOT NULL,
    direction      text NOT NULL CHECK (direction IN ('LONG', 'SHORT')),
    time_open      timestamp NOT NULL,
    time_closed    timestamp NOT NULL,
    price_open     double precision NOT NULL,
    price_closed   double precision NOT NULL,
    pnl_percentage double precision NOT NULL,
    duration_hours double precision NOT NULL,
    CONSTRAINT trading_paper_uniq UNIQUE (symbol, direction, time_open, time_closed)
);

-- 3. trading/virtual_trader.py (insert/update), reports/google_drive.py "third" (read)
--    Open position = time_closed IS NULL, so close fields are nullable.
CREATE TABLE IF NOT EXISTS public.third_option (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol         text NOT NULL,
    direction      text NOT NULL CHECK (direction IN ('LONG', 'SHORT')),
    time_open      timestamp NOT NULL,
    time_closed    timestamp,
    price_open     double precision NOT NULL,
    price_closed   double precision,
    pnl_percentage double precision,
    duration_hours double precision
);
CREATE INDEX IF NOT EXISTS third_option_open_idx
    ON public.third_option (symbol, time_open DESC) WHERE time_closed IS NULL;

-- 4. swingbot/database.py -> save_bingx_log()
CREATE TABLE IF NOT EXISTS public.bingx_order_logs (
    id                bigserial PRIMARY KEY,
    created_at        timestamp NOT NULL DEFAULT now(),
    symbol            text,
    direction         text,
    action            text,
    status            text,
    message           text,
    exchange_response jsonb
);

-- 5. reports/telegram_bot.py -> get_csv_from_db()
--    NOTE: separate table from trading_paper (column is time_close, not time_closed).
CREATE TABLE IF NOT EXISTS public.paper_trading (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol         text NOT NULL,
    direction      text NOT NULL,
    pnl_percentage double precision,
    time_open      timestamp,
    time_close     timestamp
);

